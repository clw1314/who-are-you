#!/usr/bin/env node
// Writes src/tz.mjs: the country of every IANA time zone, old names included, from the tz database's zone.tab and
// backward files. The page uses it to tell which country a system time zone belongs to.
// Usage: node scripts/tz.mjs   (fetches the current files from github.com/eggert/tz)
import { writeFile } from "node:fs/promises";

const get = async f => { const r = await fetch("https://raw.githubusercontent.com/eggert/tz/main/" + f); if (!r.ok) throw new Error(f + ": HTTP " + r.status); return r.text(); };
const [tab, back] = await Promise.all([get("zone.tab"), get("backward")]);
const cc = {};
for (const line of tab.split("\n")) {
  if (!line || line[0] === "#") continue;
  const [c, , zone] = line.split("\t");
  cc[zone] = c;
}
// "Link  TARGET  ALIAS": an old name gets its target's country
for (const line of back.split("\n")) {
  const m = line.match(/^Link\s+(\S+)\s+(\S+)/);
  if (m && cc[m[1]] && !cc[m[2]]) cc[m[2]] = cc[m[1]];
}
const zones = Object.keys(cc).sort();
await writeFile(new URL("../src/tz.mjs", import.meta.url),
  "// Generated by scripts/tz.mjs from the tz database (zone.tab, backward): time zone → ISO country code.\n" +
  "export const TZ_CC = " + JSON.stringify(Object.fromEntries(zones.map(z => [z, cc[z]]))) + ";\n");
console.log(zones.length + " zones");
